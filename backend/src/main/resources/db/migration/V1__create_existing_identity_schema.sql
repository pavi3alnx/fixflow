-- Reproduce the supplied existing identity schema; do not apply to existing tables.
CREATE TABLE public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT roles_pkey PRIMARY KEY (id),
    CONSTRAINT roles_name_key UNIQUE (name)
);

CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    student_staff_id VARCHAR(50) NOT NULL,
    department VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role_id BIGINT NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_student_staff_id_key UNIQUE (student_staff_id),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES public.roles(id)
);
