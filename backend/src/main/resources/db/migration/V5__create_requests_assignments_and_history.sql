CREATE TABLE public.maintenance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL,
    building_id BIGINT NOT NULL,
    room_id BIGINT,
    category_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    suggested_priority VARCHAR(10) NOT NULL,
    priority VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_requests_reporter FOREIGN KEY (reporter_id) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_requests_building FOREIGN KEY (building_id) REFERENCES public.buildings(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_requests_building_room FOREIGN KEY (building_id, room_id)
        REFERENCES public.rooms(building_id, id) MATCH SIMPLE
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_requests_category FOREIGN KEY (category_id) REFERENCES public.categories(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_requests_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_requests_description CHECK (btrim(description) <> ''),
    CONSTRAINT ck_requests_suggested_priority CHECK (suggested_priority IN ('LOW','MEDIUM','HIGH','URGENT')),
    CONSTRAINT ck_requests_priority CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')),
    CONSTRAINT ck_requests_status CHECK (status IN ('OPEN', 'VERIFIED', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CONFIRMED', 'CLOSED', 'REJECTED', 'ON_HOLD', 'REOPENED'))
);
CREATE INDEX ix_requests_reporter_created ON public.maintenance_requests(reporter_id, created_at DESC, id DESC);
CREATE INDEX ix_requests_location ON public.maintenance_requests(building_id, room_id);
CREATE INDEX ix_requests_category ON public.maintenance_requests(category_id);
CREATE INDEX ix_requests_status_created ON public.maintenance_requests(status, created_at DESC, id DESC);

CREATE TABLE public.assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    technician_id BIGINT NOT NULL,
    assigned_by BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    accepted_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    repair_notes TEXT,
    ended_at TIMESTAMPTZ,
    end_reason VARCHAR(20),
    CONSTRAINT fk_assignments_request FOREIGN KEY (request_id) REFERENCES public.maintenance_requests(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_assignments_technician FOREIGN KEY (technician_id) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_assignments_admin FOREIGN KEY (assigned_by) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_assignments_accepted CHECK (accepted_at IS NULL OR accepted_at >= assigned_at),
    CONSTRAINT ck_assignments_started CHECK (started_at IS NULL OR
        (accepted_at IS NOT NULL AND started_at >= accepted_at)),
    CONSTRAINT ck_assignments_resolved CHECK (resolved_at IS NULL OR
        (started_at IS NOT NULL AND resolved_at >= started_at)),
    CONSTRAINT ck_assignments_end_pair CHECK ((ended_at IS NULL) = (end_reason IS NULL)),
    CONSTRAINT ck_assignments_end_reason CHECK (end_reason IN ('REASSIGNED', 'RESOLVED')),
    CONSTRAINT ck_assignments_ended CHECK (ended_at IS NULL OR
        (ended_at >= assigned_at AND (accepted_at IS NULL OR ended_at >= accepted_at)
        AND (started_at IS NULL OR ended_at >= started_at)
        AND (resolved_at IS NULL OR ended_at >= resolved_at))),
    CONSTRAINT ck_assignments_resolution CHECK (
        (resolved_at IS NULL AND (end_reason IS NULL OR end_reason <> 'RESOLVED')) OR
        (resolved_at IS NOT NULL AND ended_at IS NOT NULL AND end_reason IS NOT NULL
         AND end_reason = 'RESOLVED' AND repair_notes IS NOT NULL AND btrim(repair_notes) <> ''))
);
CREATE UNIQUE INDEX uq_assignments_current ON public.assignments(request_id) WHERE ended_at IS NULL;
CREATE INDEX ix_assignments_request_time ON public.assignments(request_id, assigned_at, id);
CREATE INDEX ix_assignments_technician ON public.assignments(technician_id, ended_at);

CREATE TABLE public.status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    changed_by BIGINT NOT NULL,
    reason TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_status_history_request FOREIGN KEY (request_id) REFERENCES public.maintenance_requests(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_status_history_actor FOREIGN KEY (changed_by) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_history_previous CHECK (previous_status IN ('OPEN', 'VERIFIED', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CONFIRMED', 'CLOSED', 'REJECTED', 'ON_HOLD', 'REOPENED')),
    CONSTRAINT ck_history_new CHECK (new_status IN ('OPEN', 'VERIFIED', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CONFIRMED', 'CLOSED', 'REJECTED', 'ON_HOLD', 'REOPENED')),
    CONSTRAINT ck_history_initial CHECK (previous_status IS NOT NULL OR new_status = 'OPEN'),
    CONSTRAINT ck_history_change CHECK (previous_status IS NULL OR previous_status <> new_status),
    CONSTRAINT ck_history_rejection CHECK (new_status <> 'REJECTED' OR
        (reason IS NOT NULL AND btrim(reason) <> ''))
);
CREATE UNIQUE INDEX uq_history_initial ON public.status_history(request_id) WHERE previous_status IS NULL;
CREATE INDEX ix_history_request_time ON public.status_history(request_id, changed_at, id);
