CREATE TABLE public.buildings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_buildings_code UNIQUE (code),
    CONSTRAINT ck_buildings_code CHECK (btrim(code) <> ''),
    CONSTRAINT ck_buildings_name CHECK (btrim(name) <> '')
);

CREATE TABLE public.rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150),
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rooms_building FOREIGN KEY (building_id) REFERENCES public.buildings(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT uq_rooms_building_code UNIQUE (building_id, code),
    CONSTRAINT uq_rooms_building_id UNIQUE (building_id, id),
    CONSTRAINT ck_rooms_code CHECK (btrim(code) <> ''),
    CONSTRAINT ck_rooms_name CHECK (name IS NULL OR btrim(name) <> '')
);

CREATE TABLE public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_categories_code UNIQUE (code),
    CONSTRAINT ck_categories_code CHECK (btrim(code) <> ''),
    CONSTRAINT ck_categories_name CHECK (btrim(name) <> '')
);
