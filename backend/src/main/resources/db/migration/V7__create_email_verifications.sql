CREATE TABLE public.email_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    email VARCHAR(255) NOT NULL,
    otp_hash VARCHAR(255) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    resend_available_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    invalidated_at TIMESTAMPTZ,
    CONSTRAINT fk_email_verifications_user FOREIGN KEY (user_id) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_verifications_text CHECK (btrim(email) <> '' AND btrim(otp_hash) <> ''),
    CONSTRAINT ck_verifications_attempts CHECK (max_attempts > 0 AND attempt_count BETWEEN 0 AND max_attempts),
    CONSTRAINT ck_verifications_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_verifications_resend CHECK (resend_available_at >= created_at),
    CONSTRAINT ck_verifications_consumed CHECK (consumed_at IS NULL OR
        (consumed_at >= created_at AND consumed_at <= expires_at)),
    CONSTRAINT ck_verifications_invalidated CHECK (invalidated_at IS NULL OR invalidated_at >= created_at),
    CONSTRAINT ck_verifications_terminal CHECK (consumed_at IS NULL OR invalidated_at IS NULL)
);
CREATE UNIQUE INDEX uq_verifications_outstanding ON public.email_verifications(user_id)
    WHERE consumed_at IS NULL AND invalidated_at IS NULL;
CREATE INDEX ix_verifications_user_time ON public.email_verifications(user_id, created_at DESC, id DESC);
CREATE INDEX ix_verifications_expiry ON public.email_verifications(expires_at);
