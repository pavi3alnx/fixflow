CREATE TABLE public.comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comments_request FOREIGN KEY (request_id) REFERENCES public.maintenance_requests(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_comments_body CHECK (btrim(body) <> '')
);
CREATE INDEX ix_comments_request_time ON public.comments(request_id, created_at, id);

CREATE TABLE public.attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    uploaded_by BIGINT NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    storage_provider VARCHAR(50) NOT NULL,
    storage_key TEXT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    media_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attachments_request FOREIGN KEY (request_id) REFERENCES public.maintenance_requests(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_attachments_uploader FOREIGN KEY (uploaded_by) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT uq_attachments_storage UNIQUE (storage_provider, storage_key),
    CONSTRAINT ck_attachments_purpose CHECK (purpose IN ('ISSUE_PHOTO', 'REPAIR_EVIDENCE')),
    CONSTRAINT ck_attachments_size CHECK (size_bytes > 0),
    CONSTRAINT ck_attachments_metadata CHECK (btrim(storage_provider) <> '' AND btrim(storage_key) <> ''
        AND btrim(original_filename) <> '' AND btrim(media_type) <> '')
);
CREATE INDEX ix_attachments_request_time ON public.attachments(request_id, created_at, id);

CREATE TABLE public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    request_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ,
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES public.users(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_notifications_request FOREIGN KEY (request_id) REFERENCES public.maintenance_requests(id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_notifications_text CHECK (btrim(event_type) <> '' AND btrim(title) <> '' AND btrim(message) <> ''),
    CONSTRAINT ck_notifications_read CHECK (read_at IS NULL OR read_at >= created_at)
);
CREATE INDEX ix_notifications_recipient_time ON public.notifications(recipient_id, created_at DESC, id DESC);
CREATE INDEX ix_notifications_unread ON public.notifications(recipient_id, created_at DESC, id DESC) WHERE read_at IS NULL;
CREATE INDEX ix_notifications_request ON public.notifications(request_id);
